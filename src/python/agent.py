def extract_text(content: Any) -> str:
    """Extract text from a LangChain response."""
    if isinstance(content, str):
        return content.strip()

    if isinstance(content, list):
        parts: list[str] = []

        for block in content:
            if isinstance(block, dict):
                text = block.get("text")

                if isinstance(text, str):
                    parts.append(text)
            elif isinstance(block, str):
                parts.append(block)

        return "".join(parts).strip()

    raise ValueError(
        "Unexpected agent response content type."
    )


def parse_json_object(
    text: str,
) -> dict[str, Any]:
    """Extract and parse a JSON object from model output."""
    cleaned = text.strip()

    if cleaned.startswith("```"):
        lines = cleaned.splitlines()

        if lines:
            lines = lines[1:]

        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]

        cleaned = "\n".join(lines).strip()

        if cleaned.lower().startswith("json"):
            cleaned = cleaned[4:].strip()

    start = cleaned.find("{")
    end = cleaned.rfind("}")

    if start < 0 or end < start:
        raise ValueError(
            "The agent response did not contain a JSON object."
        )

    result = json.loads(cleaned[start : end + 1])

    if not isinstance(result, dict):
        raise ValueError(
            "The agent response must be a JSON object."
        )

    return result


async def run_agent(
    ticket: dict[str, Any],
    llm_config_name: str = DEFAULT_LLM_CONFIG,
) -> dict[str, Any]:
    """Run the configured IRIS AI Hub model."""
    connection = iris.connect(
        "localhost",
        1972,
        "USER",
        "_SYSTEM",
        os.environ["IRIS_PASSWORD"],
    )

    try:
        model = init_chat_model(
            llm_config_name,
            connection,
        )

        agent = create_agent(
            model,
            tools=[],
        )

        ticket_json = json.dumps(
            ticket,
            ensure_ascii=False,
            indent=2,
        )

        result = await agent.ainvoke(
            {
                "messages": [
                    {
                        "role": "user",
                        "content": (
                            f"{AGENT_INSTRUCTIONS}\n\n"
                            f"Ticket:\n\n{ticket_json}"
                        ),
                    }
                ]
            }
        )

        messages = result.get("messages", [])

        if not messages:
            raise ValueError(
                "The agent returned no messages."
            )

        return parse_json_object(
            extract_text(messages[-1].content)
        )
    finally:
        connection.close()